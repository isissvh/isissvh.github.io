const spanishMonths = { ene: 0, feb: 1, mar: 2, abr: 3, may: 4, jun: 5, jul: 6, ago: 7, sep: 8, oct: 9, nov: 10, dic: 11 };
export const parsePracticeDate = (date) => {
  const [day, month, year] = date.toLocaleLowerCase("es").split(/\s+/);
  const monthIndex = spanishMonths[month?.slice(0, 3)];
  return monthIndex === undefined ? 0 : Date.UTC(Number(year), monthIndex, Number(day));
};

